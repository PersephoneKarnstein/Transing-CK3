#!/usr/bin/env python3
"""Writes common/scripted_effects/tm_tracking_effects.txt: the per-decade census kept on each faith.

CK3 cannot build variable names at run time, so each decade gets its own fixed names (tm_c0890_members ...).
Run from the repo root: python3 tools/gen_tracking.py
"""
FAITHS = ['transbian_maximalism', 'tm_baeddel', 'tm_yutai', 'tm_nehpakhot', 'tm_garland', 'tm_badenya']
METRICS = ['members', 'daughters', 'marked', 'rulers', 'counties']         # counted at each census
COUNTERS = ['joins', 'ruler_joins', 'kahal_joins', 'offers', 'rises', 'deaths']  # running totals (tm_track_effect)
DECADES = range(860, 1460, 10)

HEADER = '''﻿# Adelphai Dorleyaiou — tracking for observe runs (docs/faith_design.md §14). Writes nothing the player sees.
# Generated by tools/gen_tracking.py; edit that, not this file.
#
# Every 10 years (tm_yearly_growth) each of the six faiths takes a census and keeps it on the faith, one variable per
# decade so a single late save holds the whole run: tm_c<decade>_<what>, e.g. tm_c0890_members. <what> is
#   members, daughters, marked, rulers (landed members), counties: counted at that census;
#   joins, ruler_joins, kahal_joins, offers, rises, deaths: running totals since game start (tm_track_effect).
# Worldwide totals of Marked characters and daughters go to global variables tm_c<decade>_marked / _daughters.
# tools/census_report.py reads them out of a save.

# Adds one to a running total on a faith. $FAITH$ a faith scope, $WHAT$ one of the counters above.
tm_track_effect = {
\t$FAITH$ = { change_variable = { name = tm_n_$WHAT$ add = 1 } }
}

# A character made at game start for a seat: kept on a global list per seat (a dead character loses their own
# variables), so a save shows what became of them. Scope: the seed. $SEAT$ the seat's name, e.g. gotland.
tm_register_seed_effect = {
\tset_variable = { name = tm_seed value = flag:$SEAT$ }
\tadd_to_global_variable_list = { name = tm_seeds_$SEAT$ target = this }
}

'''


def census():
    out = ['# The census. Scope: none. Also run by tools/run/tm_census_log.txt.\n', 'tm_census_log_effect = {\n']
    for f in FAITHS:
        out.append(f'\tfaith:{f} = {{\n')
        out += [f'\t\tset_variable = {{ name = tm_t_{m} value = 0 }}\n' for m in METRICS]
        out.append('\t}\n')
    out.append('''\tevery_living_character = {
\t\tlimit = { rite ?= { rite_has_parameter = tm_sisters_faith } }
\t\tfaith = { change_variable = { name = tm_t_members add = 1 } }
\t\tif = {
\t\t\tlimit = { tm_is_daughter_trigger = yes }
\t\t\tfaith = { change_variable = { name = tm_t_daughters add = 1 } }
\t\t}
\t\tif = {
\t\t\tlimit = { has_trait = tm_transgender }
\t\t\tfaith = { change_variable = { name = tm_t_marked add = 1 } }
\t\t}
\t\tif = {
\t\t\tlimit = { is_landed = yes }
\t\t\tfaith = { change_variable = { name = tm_t_rulers add = 1 } }
\t\t}
\t}
''')
    out.append('\tevery_county = {\n\t\tlimit = { OR = { ' + ' '.join(f'faith = faith:{f}' for f in FAITHS) + ' } }\n')
    out.append('\t\tfaith = { change_variable = { name = tm_t_counties add = 1 } }\n\t}\n')
    out.append('\tsave_scope_value_as = { name = tm_w_marked value = { value = 0 every_living_character = { limit = { has_trait = tm_transgender } add = 1 } } }\n')
    out.append('\tsave_scope_value_as = { name = tm_w_daughters value = { value = 0 every_living_character = { limit = { tm_is_daughter_trigger = yes } add = 1 } } }\n')
    out.append('\tset_global_variable = { name = tm_census_year value = current_year }\n')
    for f in FAITHS:
        out.append(f'\tfaith:{f} = {{\n')
        for n, d in enumerate(DECADES):
            out.append(f'\t\t{"if" if n == 0 else "else_if"} = {{\n\t\t\tlimit = {{ current_year < {d + 10} }}\n')
            out += [f'\t\t\tset_variable = {{ name = tm_c{d:04d}_{m} value = var:tm_t_{m} }}\n' for m in METRICS]
            out += [f'\t\t\tif = {{ limit = {{ has_variable = tm_n_{c} }} set_variable = {{ name = tm_c{d:04d}_{c} value = var:tm_n_{c} }} }}\n'
                    for c in COUNTERS]
            out.append('\t\t}\n')
        out.append('\t}\n')
    for n, d in enumerate(DECADES):
        out.append(f'\t{"if" if n == 0 else "else_if"} = {{\n\t\tlimit = {{ current_year < {d + 10} }}\n')
        out.append(f'\t\tset_global_variable = {{ name = tm_c{d:04d}_marked value = scope:tm_w_marked }}\n')
        out.append(f'\t\tset_global_variable = {{ name = tm_c{d:04d}_daughters value = scope:tm_w_daughters }}\n\t}}\n')
    out.append('}\n')
    return ''.join(out)


if __name__ == '__main__':
    with open('common/scripted_effects/tm_tracking_effects.txt', 'w', encoding='utf-8') as fh:
        fh.write(HEADER + census())
